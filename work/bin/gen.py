"""Build cloud_outbox/inventory.md and manifest.json from inventory_rows.py + state.json (progress overrides)."""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from inventory_rows import ROWS
OUT = "/home/user/ClaudeBooks/cloud_outbox"
STATE = "/home/user/ClaudeBooks/work/state.json"
state = json.load(open(STATE)) if os.path.exists(STATE) else {}
rows = [r for r in ROWS if r[7] != "SKIP"]
order = {"H": 0, "M": 1, "L": 2, "": 3}
def cur(r):
    s = dict(zip(["key","title","author","drive_path","type","pages","text_layer","status","priority","notes","file_id"], r))
    s.update({k: v for k, v in state.get(s["key"], {}).items() if k in s}) if s["key"] else None
    return s
items = [cur(r) for r in rows]
L = ["# Drive inventory — strategy extraction (cloud session)", "",
     "Generated by the cloud session. One row per Drive resource; byte-identical copies are merged into one row (all paths listed).",
     "Abbreviations: `WA` = `Phone Backup Aug 2025/WhatsApp Documents`, `WA/Private` its subfolder, `invest` = `My Drive/invest`.",
     "`pages`/`text layer` are filled in when a resource is opened for extraction (`?`/`unchecked` = not opened yet).", ""]
from collections import Counter
c = Counter(i["status"] for i in items)
L.append("**Status counts (rows):** " + ", ".join(f"{k}: {v}" for k, v in sorted(c.items())))
L.append("")
L.append("| # | key | title | author | Drive path | type | pages | text layer | status | priority | notes |")
L.append("|---|---|---|---|---|---|---|---|---|---|---|")
stat_order = {"done":0,"in_progress":1,"todo":2,"needs_ocr":3,"possible_duplicate":4,"local_other_edition":5,"local_exists":6,"skipped_drm":7,"not_strategy_source":8,"video_deferred":9}
items.sort(key=lambda i: (stat_order.get(i["status"], 5), order.get(i["priority"], 3)))
esc = lambda s: str(s).replace("|", "\\|")
for n, i in enumerate(items, 1):
    L.append("| " + " | ".join(esc(x) for x in [n, i["key"], i["title"], i["author"], i["drive_path"], i["type"], i["pages"], i["text_layer"], i["status"], i["priority"], i["notes"]]) + " |")
open(f"{OUT}/inventory.md", "w").write("\n".join(L) + "\n")
man = []
for i in items:
    if not i["key"]: continue
    st = state.get(i["key"], {})
    man.append({"key": i["key"], "title": i["title"], "author": i["author"], "drive_path": i["drive_path"], "status": i["status"],
                "priority": i["priority"], "page_basis": st.get("page_basis", ""), "strategies": st.get("strategies", 0),
                "citations_ok": st.get("citations_ok", 0), "citations_checked": st.get("citations_checked", 0),
                "coverage": st.get("coverage", ""), "completed_at": st.get("completed_at", "")})
json.dump(man, open(f"{OUT}/manifest.json", "w"), indent=1, ensure_ascii=False)
print(len(items), "rows;", len(man), "manifest entries;", dict(c))
